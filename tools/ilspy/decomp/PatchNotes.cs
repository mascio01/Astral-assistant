	{
	}

	public override void PreHandleInputImpl(InputFrame inputFrame)
	{
		if (InputFunctionManager.Instance.IsJustPressed(InputFunction.Back))
		{
			SoundManager.PlayMenuSound(SoundManager.BackwardPageSound);
			WantPop = true;
		}
		RectTransform rectTransform = (RectTransform)UnityContents.transform;
		rectTransform.anchoredPosition = new Vector2(rectTransform.anchoredPosition.x, yOffset);
		yOffset -= GameImpl.UnscaledDeltaTime * ScrollSpeed * InputFunctionManager.Instance.GetAxis(InputFunction.MoveVert);
		yOffset = Mathf.Clamp(yOffset, 0f, Mathf.Max(0f, rectTransform.rect.height - HudBehaviour.Instance.HudPanelRectTransform.rect.height));
		if (AddedPatchIndex < Patches.Count - 1 && yOffset + HudBehaviour.Instance.HudPanelRectTransform.rect.height >= rectTransform.rect.height)
		{
			Patch patch = Patches[AddedPatchIndex];
			Object.Instantiate(BaseMenu.PatchNotesHeading.GetAsset(), UnityContents.transform).GetComponent<TextMeshProUGUI>().SetUnityText(patch.Heading);
			for (int i = 0; i < patch.Lines.Count; i++)
			{
				Object.Instantiate(BaseMenu.PatchNotesLine.GetAsset(), UnityContents.transform).FindChild(Notes).GetComponent<TextMeshProUGUI>()
					.SetUnityText(patch.Lines[i]);
			}
			Object.Instantiate(BaseMenu.CreditsSpacer.GetAsset(), UnityContents.transform);
			AddedPatchIndex++;
		}
	}

	public override void OnDeactivate(bool popped)
	{
		UnityContents.DeleteAllChildren();
		AddedPatchIndex = 0;
		yOffset = 0f;
		base.OnDeactivate(popped);
	}
